#!/usr/bin/env python3
"""v6566-handheld: BANTER.md (Erik: "perfect") -> tools/hh/hh_banter.js, wired word for word.
HH_BANTER[path][beat] = [ [ [who, text], ... ], ... ] ; named[who] = one exchange ; glitch = { ap, win, loss }"""
import re, json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else '/workspace/handheld/BANTER.md')
PATHS = {'Fierce': 'fierce', 'Compassionate': 'balanced', 'Strategic': 'strategic'}
BEATS = [('Challenge walk-up \u2014 named', 'named'), ('Challenge walk-up', 'walk'), ('Mid-match \u2014 first super', 'super'), ('Mid-match \u2014 low HP', 'low'),
         ('After a first win', 'first'), ('After a rematch win', 'rematch'), ('After a loss', 'loss'), ('Glitch K\u014dno', 'glitch')]
out = {}; path = beat = None; var = None
for raw in SRC.read_text(encoding='utf8').splitlines():
    ln = raw.strip()
    m = re.match(r'^## (\w+)$', ln)
    if m:
        path = PATHS.get(m.group(1)); beat = None
        if path: out[path] = {'walk': [], 'named': {}, 'super': [], 'low': [], 'first': [], 'rematch': [], 'loss': [], 'glitch': {'ap': [], 'win': [], 'loss': []}}
        continue
    if not path: continue
    m = re.match(r'^### (.+)$', ln)
    if m:
        beat = next((k for t, k in BEATS if m.group(1).startswith(t)), None); var = None; continue
    m = re.match(r'^\*\*(.+?)\*\*', ln)
    if m and beat:
        lab = m.group(1); var = []
        if beat == 'named': out[path]['named'][lab.lower()] = var
        elif beat == 'glitch':
            k = 'ap' if lab.startswith('Approach') else 'win' if lab.startswith('Win') else 'loss'; out[path]['glitch'][k].append(var)
        else: out[path][beat].append(var)
        continue
    m = re.match(r'^(Ryo|Aoi): (.+)$', ln)
    if m and var is not None: var.append([m.group(1).lower(), m.group(2)])
js = '/* generated by tools/hh/banter_js.py from BANTER.md (approved by Erik, t598u). Do not edit by hand. */\nvar HH_BANTER = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
(HERE / 'hh_banter.js').write_text(js, encoding='utf8')
n = sum(len(v) for p in out.values() for k, v in p.items() if isinstance(v, list)) + sum(len(p['named']) for p in out.values()) + sum(len(x) for p in out.values() for x in p['glitch'].values())
print('paths', list(out), 'exchanges', n, 'lines', js.count('["'))
for p, d in out.items(): print(p, {k: (len(v) if not isinstance(v, dict) else {kk: len(vv) for kk, vv in v.items()}) for k, v in d.items()})
